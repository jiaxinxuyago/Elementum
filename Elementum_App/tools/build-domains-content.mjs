// ===================================================================
// ELEMENTUM · build-domains-content — the station → src/content/domains.js
// ===================================================================
// THE DOMAINS corpus (DOM-1, owner rulings 2026-10-17) lives in the
// station:
//   POSITION/<id>.json       candidates.domain_climb{<Domain>:{headline,recognition,lived,ahead?}}
//                            (+ the rewritten defline / reading, read by positions.js as before)
//   GOD/<id>.json            candidates.decade_lines{<Domain>:{helping|heavy:{lived|ahead}}}
//   TG_PATTERN/<key>.json    candidates.domain_lines{<Domain>} + candidates.fused_line
//   TEMPLATED/tpl_domains.json  candidates.domain_gaps / domain_unruled / domain_unruled_headline
// This tool gathers them into the one module the resolver reads
// (domainsResolve.js). Run after any station change:
//   node tools/build-domains-content.mjs           write
//   node tools/build-domains-content.mjs --check   exit 1 if the module is stale
// ===================================================================
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..') + '/';
const ST = ROOT + 'Reading/Database/templates/by_axis/json/';
const OUT = ROOT + 'Elementum_App/src/content/domains.js';
const read = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));
const GOD_ZH = { bijian: '比肩', jiecai: '劫财', shishen: '食神', shangguan: '伤官', piancai: '偏财', zhengcai: '正财', qisha: '七杀', zhengguan: '正官', pianyin: '偏印', zhengyin: '正印' };

const seats = {};
for (const f of fs.readdirSync(ST + 'POSITION').filter((x) => x.endsWith('.json')).sort()) {
  const c = read(ST + 'POSITION/' + f).candidates;
  if (c.domain_climb) seats[f.replace('.json', '')] = { domains: c.domain_climb };
}
const decades = {};
for (const [id, zh] of Object.entries(GOD_ZH)) {
  const p = ST + `GOD/${id}.json`;
  const c = fs.existsSync(p) ? read(p).candidates : null;
  if (c?.decade_lines) decades[zh] = c.decade_lines;
}
const patterns = {};
for (const f of fs.readdirSync(ST + 'TG_PATTERN').filter((x) => x.endsWith('.json')).sort()) {
  const c = read(ST + 'TG_PATTERN/' + f).candidates;
  if (c.domain_lines) patterns[f.replace('.json', '')] = { readings: c.domain_lines, fused_line: c.fused_line };
}
const tplP = ST + 'TEMPLATED/tpl_domains.json';
const tpl = fs.existsSync(tplP) ? read(tplP).candidates : {};
const content = { seats, decades, patterns, gaps: tpl.domain_gaps || {}, unruled: tpl.domain_unruled || {}, unruledHeadline: tpl.domain_unruled_headline || {} };

const body = `// GENERATED by tools/build-domains-content.mjs from the station — do not edit by hand.
// THE DOMAINS corpus (DOM-1, owner rulings 2026-10-17). Read by components/reading/domainsResolve.js.
export const DOMAINS_CONTENT = ${JSON.stringify(content, null, 1)};
`;
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== body) { console.log('domains.js is stale: run node tools/build-domains-content.mjs'); process.exit(1); }
  console.log(`domains.js in sync (${Object.keys(seats).length} seats, ${Object.keys(decades).length} gods, ${Object.keys(patterns).length} pairs)`);
} else {
  fs.writeFileSync(OUT, body);
  console.log(`wrote domains.js (${Object.keys(seats).length} seats, ${Object.keys(decades).length} gods, ${Object.keys(patterns).length} pairs)`);
}
