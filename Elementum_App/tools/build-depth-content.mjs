// ===================================================================
// ELEMENTUM · build-depth-content — the in-depth units → src/content/depth.js
// ===================================================================
// Source: the gated golden templates (owner P6 A, round 8):
// ComparativeAnalysis/Prompts/out/handoff/2026-10-18-depth-template/template.json.
// Every unit is keyed by its station key ("POSITION zhengcai_year_stem ·
// chapter.lived"). Templated units carry their golden fill; their slot
// form is composed by the resolver. Until the batch lands in the station,
// the resolvers fill every unwritten unit with a draft line (owner B3).
//   node tools/build-depth-content.mjs           # write
//   node tools/build-depth-content.mjs --check   # exit 1 if stale
// ===================================================================
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.resolve(APP, '../ComparativeAnalysis/Prompts/out/handoff/2026-10-18-depth-template/template.json');
const OUT = path.join(APP, 'src/content/depth.js');
const { units } = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const map = {};
// units with slots are composed by the resolver; the rest are written once for every chart
for (const u of units) if (!u.slots) map[u.key] = u.text;
const body = `// GENERATED by tools/build-depth-content.mjs from the round-8 golden templates. Do not edit by hand.
// The in-depth units written so far, keyed by station key. Unwritten units are drafted by depthResolve.js.
export const DEPTH_UNITS = ${JSON.stringify(map, null, 1)};
`;
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== body) { console.log('depth.js is stale: run node tools/build-depth-content.mjs'); process.exit(1); }
  console.log(`depth.js is current (${Object.keys(map).length} units).`);
} else { fs.writeFileSync(OUT, body); console.log(`wrote src/content/depth.js (${Object.keys(map).length} units)`); }
