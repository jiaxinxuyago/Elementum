// ===================================================================
// ELEMENTUM · build-depth-content — the in-depth units, station → app
// ===================================================================
// The corpus lives in the station (owner R2 A, 2026-10-21: "Land everything
// in the station, generate the content modules from it"):
//   TEMPLATED/tpl_depth.json   candidates.units { "<app key>": text }
// keyed exactly as depthResolve.js reads them:
//   GOD <god> · missing | seen.plain | seen.inside | season_need.<shown|rooted|hidden> | year_domain.<Domain>
//   STRUCTURE <id>_ge · reading           STRUCTURE <family> · status.<state>.<breaker>
//   SEASON <stem>.<branch> · reading      TG_PATTERN <key> · blueprint_line
//   TEMPLATED tpl_depth · bond.<type>.<gates> | bond.none_hard | seen.close
//   TEMPLATED tpl_depth · structure_rule.<how> | rescue.<family>[.lived|.none] | strongest.<one|two>
//     (slot templates: {element} {count} {god} {holder} {when} {a} {b} {share} {a_noun} {b_noun}
//      {breakers} {stand} {gods}, filled by the resolver)
// plus the round-8 golden units of the other sections, which those sections
// supersede with their own modules (depthChapters*.js, depthStars.js).
//   node tools/build-depth-content.mjs --adopt <handoff dir>   gate approved.json + out-*.json, merge into the station
//   node tools/build-depth-content.mjs                          station → src/content/depth.js
//   node tools/build-depth-content.mjs --check                  exit 1 if the module is stale
// ===================================================================
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..') + '/';
const ST = ROOT + 'Reading/Database/templates/by_axis/json/TEMPLATED/tpl_depth.json';
const OUT = ROOT + 'Elementum_App/src/content/depth.js';
const argv = process.argv.slice(2);

if (argv[0] === '--adopt') {
  const dir = path.resolve(argv[1]);
  const files = fs.readdirSync(dir).filter((f) => /^(approved|out-.+)\.json$/.test(f)).sort();
  execFileSync('node', [path.join(dir, 'gate.mjs'), ...files.map((f) => path.join(dir, f))], { stdio: 'inherit', cwd: dir });
  const prev = JSON.parse(fs.readFileSync(ST, 'utf8'));
  const units = { ...prev.candidates.units };
  let n = 0;
  for (const f of files) for (const u of JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')).units) { units[u.key] = u.template || u.text; n++; }
  prev.candidates.units = Object.fromEntries(Object.keys(units).sort().map((k) => [k, units[k]]));
  const rel = path.relative(ROOT, dir);
  prev.$provenance = [...(prev.$provenance || []), { adopted_from: rel, files, count: n, date: new Date().toISOString().slice(0, 10), gate: rel + '/gate.mjs PASS' }];
  fs.writeFileSync(ST, JSON.stringify(prev, null, 2) + '\n');
  console.log(`station: adopted ${n} units from ${rel} (${Object.keys(units).length} in TEMPLATED/tpl_depth.json)`);
}

const st = JSON.parse(fs.readFileSync(ST, 'utf8'));
const body = `// GENERATED by tools/build-depth-content.mjs from the station (TEMPLATED/tpl_depth.json). Do not edit by hand.
// The in-depth units keyed as depthResolve.js reads them; {slots} are filled by the resolver.
export const DEPTH_UNITS = ${JSON.stringify(st.candidates.units, null, 1)};
`;
if (argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== body) { console.log('depth.js is stale: run node tools/build-depth-content.mjs'); process.exit(1); }
  console.log(`depth.js in sync (${Object.keys(st.candidates.units).length} units)`);
} else {
  fs.writeFileSync(OUT, body);
  console.log(`wrote src/content/depth.js (${Object.keys(st.candidates.units).length} units)`);
}
