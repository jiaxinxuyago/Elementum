// ===================================================================
// ELEMENTUM · build-depth-samples — the sections' own sample units
// ===================================================================
// Owner 2026-10-21: "if they have some content ready, at least ready to
// implement (unruled, unpolished are fine), pipe them into our dev link".
// Each in-depth section gets its own generated module, so no session
// regenerates another's content (04_DEPTH_STATE §3):
//   (Life Chapters left this tool on 2026-10-21: its corpus is in the station, built by tools/build-chapters-content.mjs; A4)
//   Stars         · ComparativeAnalysis/Prompts/out/handoff/2026-10-19-stars/samples.json             → src/content/depthStars.js
// The units are keyed by station key, like src/content/depth.js; a sample
// supersedes the round-8 template for the same key (the newer writing).
// Unruled: round 1 (Life Chapters, Q1–Q14) and round 9 (Stars, N0/G0/N13)
// are waiting on the owner. When a batch lands in the station, the owning
// session replaces its module from the station.
//   node tools/build-depth-samples.mjs           # write
//   node tools/build-depth-samples.mjs --check   # exit 1 if stale
// ===================================================================
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const HO = path.resolve(APP, '../ComparativeAnalysis/Prompts/out/handoff');
const SETS = [
  { src: '2026-10-19-stars/samples.json', out: 'depthStars.js', name: 'STAR_UNITS', what: 'Stars round 9 (33 samples, unruled: N0, G0, N13)' },
];
let stale = 0;
for (const s of SETS) {
  const { units } = JSON.parse(fs.readFileSync(path.join(HO, s.src), 'utf8'));
  const map = {};
  for (const u of units) if (!u.slots) map[u.key] = u.text;
  const body = `// GENERATED by tools/build-depth-samples.mjs from ${s.src}. Do not edit by hand.
// ${s.what}. Keyed by station key; depthResolve.js reads these before the round-8 templates.
export const ${s.name} = ${JSON.stringify(map, null, 1)};
`;
  const fp = path.join(APP, 'src/content', s.out);
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(fp) ? fs.readFileSync(fp, 'utf8') : '';
    if (cur !== body) { console.log(`${s.out} is stale: run node tools/build-depth-samples.mjs`); stale++; }
    else console.log(`${s.out} is current (${Object.keys(map).length} units).`);
  } else { fs.writeFileSync(fp, body); console.log(`wrote src/content/${s.out} (${Object.keys(map).length} units)`); }
}
if (stale) process.exit(1);
