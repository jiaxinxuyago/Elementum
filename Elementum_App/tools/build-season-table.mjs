// Source of truth: ComparativeAnalysis/Handoffs/2026-10-17-domains/research/
// qiongtong-tiaohou.json (120 cells, the Wikisource text checked against
// 古文岛, 徐乐吾's 造化元钥评注 and the common summary table; owner W14 A:
// the text over the summary table). Keeps what the engine reads: the stems
// asked for (primary, then secondary), the stems avoided, and the text's
// conditional stems with their condition.
//   node tools/build-season-table.mjs           # write
//   node tools/build-season-table.mjs --check   # exit 1 if the module is stale
// ===================================================================
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.resolve(APP, '../ComparativeAnalysis/Handoffs/2026-10-17-domains/research/qiongtong-tiaohou.json');
const OUT = path.join(APP, 'src/engine/depth/seasonTable.js');
const { table } = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const cells = {};
for (const [stem, months] of Object.entries(table)) {
  cells[stem] = {};
  for (const [branch, c] of Object.entries(months)) {
    cells[stem][branch] = { month: c.month, primary: c.primary, secondary: c.secondary || [], avoid: c.avoid || [], conditional: (c.conditional || []).map(({ stem: s, when }) => ({ stem: s, when })) };
  }
}
const body = `// GENERATED by tools/build-season-table.mjs from research/qiongtong-tiaohou.json. Do not edit by hand.
// 穷通宝鉴 调候: for each Day Master (stem) in each birth month (month branch), the stems the season asks for.
export const SEASON_TABLE = ${JSON.stringify(cells)};
`;
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== body) { console.log('seasonTable.js is stale: run node tools/build-season-table.mjs'); process.exit(1); }
  console.log('seasonTable.js is current.');
} else { fs.writeFileSync(OUT, body); console.log('wrote', path.relative(APP, OUT)); }
