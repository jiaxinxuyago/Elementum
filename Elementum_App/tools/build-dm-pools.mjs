// ===================================================================
// ELEMENTUM · build-dm-pools — the Day Master gifts and shadows, station first
// ===================================================================
// The door-tagged pools (REA_02 §5h): per stem, a gift face and a shadow face
// for each of the five functions (Body and Mind doubled). Hibernating in the
// station's __ore from 2026-10-17, revived 2026-10-27 for the Day Master page
// (owner: the page reads the five energies as gifts and shadows).
//   node tools/build-dm-pools.mjs           transcribe the station into src/content/dmPools.js
//   node tools/build-dm-pools.mjs --check   exit 1 if dmPools.js is stale
// The station is the editing surface: later edits go there, then transcribe.
// ===================================================================
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ST = path.resolve(APP, '../Reading/Database/templates/by_axis/json/STEM');
const OUT = path.join(APP, 'src/content/dmPools.js');
const STEMS = { jia: '甲', yi: '乙', bing: '丙', ding: '丁', wu: '戊', ji: '己', geng: '庚', xin: '辛', ren: '壬', gui: '癸' };

const pools = {};
for (const [id, hz] of Object.entries(STEMS)) {
  const c = JSON.parse(fs.readFileSync(path.join(ST, `${id}.json`), 'utf8')).candidates;
  // `dim` and `echo_of` are authoring metadata and stay station-side (REA_16 §3)
  const keep = (l) => l.map(({ dim, echo_of, ...it }) => it); // eslint-disable-line no-unused-vars
  pools[hz] = { gifts: keep(c.gifts), shadows: keep(c.shadows), door_note: c.door_note };
}
const body = `// GENERATED by tools/build-dm-pools.mjs from the station (STEM/*.json gifts, shadows, door_note). Do not edit by hand.
// The Day Master page's five energies: a gift face through a catalyst, a shadow face through a friction (owner 2026-10-27).
export const DM_POOLS = ${JSON.stringify(pools, null, 2)};
`;
const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
if (process.argv.includes('--check')) {
  if (cur !== body) { console.log('✗ dmPools.js is stale: run node tools/build-dm-pools.mjs'); process.exit(1); }
  console.log(`dmPools.js is current (${Object.keys(pools).length} stems).`);
} else {
  fs.writeFileSync(OUT, body);
  console.log(`dmPools.js written (${Object.keys(pools).length} stems).`);
}
