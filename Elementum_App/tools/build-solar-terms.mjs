// ELEMENTUM · build-solar-terms — the minute-exact 节 table (owner F1 A)
// ===================================================================
// The twelve month-opening solar terms (节) for 1900–2100, from the Sun's
// apparent ecliptic longitude (Meeus, Astronomical Algorithms ch. 25, low
// accuracy: ±0.01°, about ±15 minutes) with ΔT applied. Each term is the
// instant the longitude crosses its mark; the app turns it into a local
// date on the reader's device. Writes src/engine/almanac/solarTerms.js.
//   node tools/build-solar-terms.mjs          # write the table
//   node tools/build-solar-terms.mjs --check  # spot-check known instants
// ===================================================================
import fs from 'fs';

const OUT = new URL('../src/engine/almanac/solarTerms.js', import.meta.url);
// index 0 = 小寒 (the 丑 month), as calculator.js SOLAR_TERMS
const NAMES = ['小寒', '立春', '惊蛰', '清明', '立夏', '芒种', '小暑', '立秋', '白露', '寒露', '立冬', '大雪'];
const LON = [285, 315, 345, 15, 45, 75, 105, 135, 165, 195, 225, 255];
const APPROX = [[1, 6], [2, 4], [3, 6], [4, 5], [5, 6], [6, 6], [7, 7], [8, 7], [9, 8], [10, 8], [11, 7], [12, 7]];
const rad = (d) => (d * Math.PI) / 180;
const norm = (d) => ((d % 360) + 360) % 360;

// ΔT in seconds (Espenak–Meeus polynomials, enough for minutes)
function deltaT(y) {
  if (y < 1920) { const t = y - 1900; return -2.79 + 1.494119 * t - 0.0598939 * t ** 2 + 0.0061966 * t ** 3 - 0.000197 * t ** 4; }
  if (y < 1941) { const t = y - 1920; return 21.2 + 0.84493 * t - 0.0761 * t ** 2 + 0.0020936 * t ** 3; }
  if (y < 1961) { const t = y - 1950; return 29.07 + 0.407 * t - t ** 2 / 233 + t ** 3 / 2547; }
  if (y < 1986) { const t = y - 1975; return 45.45 + 1.067 * t - t ** 2 / 260 - t ** 3 / 718; }
  if (y < 2005) { const t = y - 2000; return 63.86 + 0.3345 * t - 0.060374 * t ** 2 + 0.0017275 * t ** 3 + 0.000651814 * t ** 4 + 0.00002373599 * t ** 5; }
  if (y < 2050) { const t = y - 2000; return 62.92 + 0.32217 * t + 0.005589 * t ** 2; }
  return -20 + 32 * ((y - 1820) / 100) ** 2 - 0.5628 * (2150 - y);
}
// apparent solar longitude at a UTC instant (ms)
function sunLon(ms) {
  const y = new Date(ms).getUTCFullYear();
  const jd = ms / 86400000 + 2440587.5 + deltaT(y) / 86400;
  const T = (jd - 2451545) / 36525;
  const L0 = 280.46646 + 36000.76983 * T + 0.0003032 * T * T;
  const M = rad(357.52911 + 35999.05029 * T - 0.0001537 * T * T);
  const C = (1.914602 - 0.004817 * T - 0.000014 * T * T) * Math.sin(M) + (0.019993 - 0.000101 * T) * Math.sin(2 * M) + 0.000289 * Math.sin(3 * M);
  const om = rad(125.04 - 1934.136 * T);
  return norm(L0 + C - 0.00569 - 0.00478 * Math.sin(om));
}
export function termInstant(year, i) {
  const [m, d] = APPROX[i]; let lo = Date.UTC(year, m - 1, d - 3), hi = Date.UTC(year, m - 1, d + 3);
  const diff = (ms) => ((sunLon(ms) - LON[i] + 540) % 360) - 180; // negative before the mark
  for (let k = 0; k < 40; k++) { const mid = (lo + hi) / 2; if (diff(mid) < 0) lo = mid; else hi = mid; }
  return Math.round(hi / 60000) * 60000;
}

if (process.argv.includes('--check')) {
  // known instants (UTC), Hong Kong Observatory / Purple Mountain tables
  const KNOWN = [[2024, 1, '2024-02-04T08:27'], [2025, 1, '2025-02-03T14:10'], [2026, 1, '2026-02-03T20:02'], [2027, 1, '2027-02-04T01:46'], [2025, 9, '2025-10-08T00:41'], [2025, 10, '2025-11-07T04:04'], [1995, 1, '1995-02-04T07:13']];
  let bad = 0;
  for (const [y, i, want] of KNOWN) { const got = new Date(termInstant(y, i)).toISOString().slice(0, 16); const off = (termInstant(y, i) - Date.parse(want + 'Z')) / 60000; console.log(`${y} ${NAMES[i]} got ${got} want ${want} (${off >= 0 ? '+' : ''}${off} min)`); if (Math.abs(off) > 20) bad++; }
  process.exit(bad ? 1 : 0);
}

const FROM = 1900, TO = 2100; const rows = [];
for (let y = FROM; y <= TO; y++) rows.push(LON.map((_, i) => Math.round((termInstant(y, i) - Date.UTC(y, 0, 1)) / 60000).toString(36)).join(','));
fs.writeFileSync(OUT, `// GENERATED by tools/build-solar-terms.mjs — do not edit. The twelve 节 (index 0 = 小寒) for ${FROM}–${TO},\n// as minutes after 1 January 00:00 UTC of the year, base 36. Meeus ch. 25, ±15 minutes.\nconst FROM = ${FROM}; const TO = ${TO};\nconst ROWS = ${JSON.stringify(rows.join(';'))}.split(';').map((r) => r.split(',').map((x) => parseInt(x, 36)));\nexport const TERM_NAMES = ${JSON.stringify(NAMES)};\n/** The UTC instant (ms) of term i (0 = 小寒 … 11 = 大雪) in a Gregorian year, or null outside ${FROM}–${TO}. */\nexport function termInstant(year, i) { if (year < FROM || year > TO) return null; return Date.UTC(year, 0, 1) + ROWS[year - FROM][i] * 60000; }\n`);
console.log(`wrote ${rows.length} years`);
