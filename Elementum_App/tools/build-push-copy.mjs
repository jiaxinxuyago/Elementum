// ===================================================================
// ELEMENTUM · build-push-copy — Your Almanac's reminder copy → the push worker
// ===================================================================
// The phone posts codes ('Fire.order.grow:clash.hour', P1 A); the worker
// composes the reminder from this table: the headline's two halves and the
// push body. Generated from src/content/almanac.js (run after it changes;
// build-almanac-content.mjs calls this). The worker is deployed by the
// owner, never by an agent.
//   node tools/build-push-copy.mjs
// ===================================================================
import fs from 'fs';
const { ALMANAC_UNITS: U } = await import('../src/content/almanac.js');
const pick = (prefix) => Object.fromEntries(Object.entries(U).filter(([k]) => k.startsWith(prefix)).map(([k, v]) => [k.slice(prefix.length), v]));
const copy = { HEAD_ENERGY: pick('TEMPLATED tpl_almanac · head.energy.'), HEAD_LAND: pick('TEMPLATED tpl_almanac · head.'), PUSH: pick('PUSH · ') };
for (const k of Object.keys(copy.HEAD_LAND)) if (k.startsWith('energy.')) delete copy.HEAD_LAND[k];
fs.writeFileSync(new URL('../workers/push/almanacCopy.js', import.meta.url), `// GENERATED by tools/build-push-copy.mjs from src/content/almanac.js. Do not edit by hand.\nexport const ALMANAC_COPY = ${JSON.stringify(copy, null, 1)};\n`);
console.log(`push copy: ${Object.keys(copy.HEAD_ENERGY).length} energy halves, ${Object.keys(copy.HEAD_LAND).length} landing halves, ${Object.keys(copy.PUSH).length} bodies`);
