// ===================================================================
// ELEMENTUM · build-stars-content — the Stars (神煞) corpus
// ===================================================================
// Owner round 9 v5, all A (2026-11-14; record:
// ComparativeAnalysis/Handoffs/2026-10-19-stars-content/03_RULINGS.md).
// The corpus lives in the station:
//   TEMPLATED/tpl_stars.json   candidates.units { "<app key>": text }
// keyed as the app reads them (depthResolve.js resolveStars):
//   STAR <id> · line | line.arriving
//   STAR <id> · reading.<year|month|day|hour>.<lived|now|coming>
//   STAR <id> · arriving.decade.<now|coming> | arriving.year
//   TEMPLATED tpl_stars · star_void.<help|test>
//   node tools/build-stars-content.mjs --adopt <handoff dir>   gate, then write the station from the handoff
//   node tools/build-stars-content.mjs                          station → src/content/depthStars.js
//   node tools/build-stars-content.mjs --check                  exit 1 if the module is stale
// Texts the batch replaces (the round-9 samples, the round-8 templates) go to
// candidates.__ore.retired: retired text is never deleted.
// ===================================================================
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..') + '/';
const ST = ROOT + 'Reading/Database/templates/by_axis/json/TEMPLATED/tpl_stars.json';
const OUT = ROOT + 'Elementum_App/src/content/depthStars.js';
const argv = process.argv.slice(2);

if (argv[0] === '--adopt') {
  const dir = path.resolve(argv[1]); const today = new Date().toISOString().slice(0, 10);
  const files = ['approved.json', ...fs.readdirSync(dir).filter((f) => /^out-.+\.json$/.test(f)).sort()];
  execFileSync('node', [path.join(dir, 'gate.mjs'), ...files.map((f) => path.join(dir, f)), '--all'], { stdio: 'inherit' });
  const units = {};
  for (const f of files) for (const u of JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')).units) units[u.key] = u.text;
  const sorted = Object.fromEntries(Object.keys(units).sort().map((k) => [k, units[k]]));
  const prev = fs.existsSync(ST) ? JSON.parse(fs.readFileSync(ST, 'utf8')) : null;
  // the texts this batch replaces: the station's own, else the module the app read before (samples and round-8 templates)
  const before = { ...(await import(ROOT + 'Elementum_App/src/content/depth.js')).DEPTH_UNITS };
  for (const k of Object.keys(before)) if (!k.startsWith('STAR ')) delete before[k];
  if (fs.existsSync(OUT)) Object.assign(before, (await import(OUT + '?t=' + Date.now())).STAR_UNITS);
  Object.assign(before, prev?.candidates?.units || {});
  const retired = Object.entries(before).filter(([k, t]) => units[k] !== t).map(([k, t]) => ({ key: k, text: t, replaced_by: units[k] ? 'batch ' + path.basename(dir) : '', why: 'owner round 9 v5 all A (2026-11-14): P3, G0, the ruled names', date: today }));
  const rel = path.relative(ROOT, dir);
  const doc = {
    $archetype: 'tpl_stars', axis: 'TEMPLATED', key: 'tpl_stars',
    canonical_name: 'STARS (神煞): the guests who visit your gates, read by star, gate and tense',
    construct: 'Station-only (owner round 9 v5, all A, 2026-11-14): 19 stars as guests (N0: two-word names). Each star has a tense-free chip line, a line and a reading for each decade it visits with (now, coming), a year unit true for any of the next five years, and a reading for each gate it can visit by the reader\'s tense (S3, S8). Readings say what the guest gives, its cost and where it works best (P3), with the gate in words (G1 ages), no events, no advice. Two Empty Seat notes (S4).',
    candidate_note: 'Owner-ruled 2026-11-14 (round 9 v5: N0, G0, C0, N13, P3, L1, N1–N19, H1–H10, S1–S10 all A).',
    sources: ['ComparativeAnalysis/Handoffs/2026-10-19-stars-content/03_RULINGS.md', rel + '/BRIEF.md'],
    candidates: { units: sorted, __ore: { ...(prev?.candidates?.__ore || {}), retired: [...(prev?.candidates?.__ore?.retired || []), ...retired] } },
    $provenance: [...(prev?.$provenance || []), { adopted_from: rel, files, count: Object.keys(sorted).length, retired: retired.length, date: today, ruling: 'owner round 9 v5 all A (2026-11-14)', gate: rel + '/gate.mjs --all PASS' }],
  };
  fs.writeFileSync(ST, JSON.stringify(doc, null, 2) + '\n');
  console.log(`station: wrote ${Object.keys(sorted).length} units to TEMPLATED/tpl_stars.json (${retired.length} earlier texts into __ore)`);
}

const st = JSON.parse(fs.readFileSync(ST, 'utf8'));
const body = `// GENERATED by tools/build-stars-content.mjs from the station (TEMPLATED/tpl_stars.json) — do not edit by hand.
// Stars, the guests who visit your gates (owner round 9 v5, all A, 2026-11-14). Read by components/reading/depthResolve.js.
export const STAR_UNITS = ${JSON.stringify(st.candidates.units, null, 1)};
`;
if (argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== body) { console.log('depthStars.js is stale: run node tools/build-stars-content.mjs'); process.exit(1); }
  console.log(`depthStars.js in sync (${Object.keys(st.candidates.units).length} units)`);
} else {
  fs.writeFileSync(OUT, body);
  console.log(`wrote src/content/depthStars.js (${Object.keys(st.candidates.units).length} units)`);
}
